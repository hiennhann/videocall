class AuthError(Exception):
    def __init__(
        self,
        code: ErrorCode,
        *,
        retry_after: int | None = None,
        fields: dict[str, str] | None = None,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(code)
        self.code = code
        self.retry_after = retry_after
        self.fields = fields
        self.details = details
