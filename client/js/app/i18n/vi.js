export function translate(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = vi[node.dataset.i18n];
  }
  for (const [attribute, target] of [["data-i18n-label", "aria-label"], ["data-i18n-placeholder", "placeholder"]]) {
    for (const node of root.querySelectorAll(`[${attribute}]`)) {
      node.setAttribute(target, vi[node.getAttribute(attribute)]);
    }
  }
}
